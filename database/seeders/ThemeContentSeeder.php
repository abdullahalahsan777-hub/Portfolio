    {
        $dataset = $this->getCompleteThemeData();

        foreach ($dataset as $theme => $pages) {
            // Store preview image under general page
            ThemeContent::updateOrCreate(
                ['theme' => $theme, 'page' => 'general', 'key' => 'template_preview_image'],
                ['section' => 'general', 'value' => "images/templates/{$theme}.png", 'type' => 'image']
            );

            foreach ($pages as $page => $sections) {
                foreach ($sections as $section => $fields) {
                    foreach ($fields as $key => [$value, $type]) {
                        ThemeContent::updateOrCreate(
                            ['theme' => $theme, 'page' => $page, 'key' => $key],
                            ['section' => $section, 'value' => $value, 'type' => $type]
                        );
                    }
                }
            }
        }
    }

